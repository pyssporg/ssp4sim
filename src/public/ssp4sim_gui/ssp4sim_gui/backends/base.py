"""Control-backend contract.

A backend is the only place that knows how to reach a simulation engine. The
GUI and its HTTP API depend on this protocol only, so a different engine can be
plugged in by writing another backend (subprocess CLI, REST service, in-process
Python API) without touching the result readers or the frontend.

The daemon backend speaks newline-delimited JSON over an AF_UNIX socket: see
``ssp4sim_gui.backends.daemon``. The offline backend is a no-op used when the
GUI only opens existing result files.
"""

from __future__ import annotations

import queue
import time
from dataclasses import dataclass, field
from typing import Any, Dict, Optional, Protocol, runtime_checkable


@dataclass(frozen=True)
class Event:
    """One asynchronous engine message.

    ``kind`` mirrors the daemon event name (``state``, ``time``, ``done``,
    ``error``) or is ``backend`` for connection-status changes generated by the
    backend itself. ``data`` is the parsed message payload.
    """

    kind: str
    data: Dict[str, Any]
    at: float = field(default_factory=time.time)


class BackendError(RuntimeError):
    """Transport or protocol failure. ``code`` is stable and machine-readable."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


@runtime_checkable
class EngineBackend(Protocol):
    """Command channel plus a fan-out stream of engine events."""

    name: str

    def status(self) -> Dict[str, Any]:
        """Return ``{"backend", "connected", "detail", ...}``."""
        ...

    def send(self, request: Dict[str, Any], timeout: float = 10.0) -> Dict[str, Any]:
        """Send one command and return the raw response envelope.

        The backend assigns protocol version and request id itself; callers must
        not supply ``v`` or ``id``. Protocol-level ``{"ok": false}`` responses
        are returned as-is. Transport failures raise :class:`BackendError`.
        """
        ...

    def subscribe(self) -> "queue.Queue[Event]":
        """Return a queue receiving every future event for this subscriber."""
        ...

    def unsubscribe(self, subscription: "queue.Queue[Event]") -> None:
        ...

    def close(self) -> None:
        ...


def publish(
    subscriptions: Dict[int, "queue.Queue[Event]"],
    event: Event,
    *,
    max_pending: int = 2000,
) -> None:
    """Fan one event out to subscribers, dropping the oldest non-critical entry.

    ``time`` events are advisory; if a browser stops reading we must not grow
    memory without bound. ``state``/``done``/``error`` are never dropped.
    """

    critical = ("state", "done", "error")
    for sub in list(subscriptions.values()):
        if sub.qsize() >= max_pending:
            try:
                victim: Optional[Event] = sub.get_nowait()
            except queue.Empty:
                victim = None
            if victim is not None and victim.kind in critical:
                sub.put_nowait(victim)
        try:
            sub.put_nowait(event)
        except queue.Full:
            pass
